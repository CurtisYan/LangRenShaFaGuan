// 每个既有角色组合转为自定义板子后，首夜身份确认和行动应能完整结束。
for (const preset of boards) {
  const custom = buildCustomBoard(preset.roleCounts)
  game = engine.makeFirstNightIdentityGame(custom)
  let steps = 200
  while (!engine.guidedFirstNightReadyToSettle(game, custom) && --steps) {
    const prompt = engine.getIdentityAssignmentPrompt(game, custom)
    if (prompt) {
      game.seats.filter(seat => !seat.roleId).slice(0, prompt.required).forEach(seat => engine.toggleIdentityAssignmentSeat(game, custom, seat.number))
      engine.completeIdentityAssignment(game, custom)
    } else {
      const card = engine.getGuidedFirstNightAction(game, custom)
      assert.ok(card, preset.name)
      if (card.enabled && !card.optional) {
        if (card.kind === 'target') engine.setNightActionTarget(game, card.id, card.targetNumbers[0])
        if (card.kind === 'multiTarget') card.targetNumbers.slice(0, card.targetCount).forEach(number => engine.toggleNightActionTarget(game, card.id, number, card.targetCount))
      }
      engine.completeGuidedFirstNightAction(game, custom)
    }
  }
  assert.ok(steps, `${preset.name}的自定义组合首夜不可卡住`)
  engine.settleNight(game)
}
